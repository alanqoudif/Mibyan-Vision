// Generates the built-in Sense seed migration from the catalog (single source of truth).
import { BUILTIN_SENSES } from '../src/sense/catalog.ts';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines = ['-- Generated by packages/shared/scripts/seed-sql.ts. Built-in Senses (owner null, published).'];
for (const s of BUILTIN_SENSES) {
  lines.push(`insert into public.vision_senses(id, owner_id, kind, category, is_public, latest_version) values (${q(s.id)}, null, 'builtin', ${q(s.category)}, true, ${q(s.version)}) on conflict (id) do update set latest_version = excluded.latest_version, category = excluded.category;`);
  lines.push(`insert into public.vision_sense_versions(sense_id, version, manifest, status) values (${q(s.id)}, ${q(s.version)}, ${q(JSON.stringify(s))}::jsonb, 'published') on conflict (sense_id, version) do update set manifest = excluded.manifest, status = 'published';`);
}
console.log(lines.join('\n'));
