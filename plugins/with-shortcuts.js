const SWIFT_FILE = 'MubayanShortcuts.swift';
const PHRASES_FILE = 'AppShortcuts.xcstrings';
const TITLES_FILE = 'Localizable.xcstrings';

const swiftString = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$\{applicationName\}/g, '\\(.applicationName)')}"`;

function swiftSource() {
  const intents = SHORTCUTS.map(
    (s) => `struct ${s.id}Intent: RouteIntent {
  static let title: LocalizedStringResource = ${swiftString(s.title[0])}
  static let route = ${swiftString(s.route)}
}`
  ).join('\n\n');
  const shortcuts = SHORTCUTS.map(
    (s) => `    AppShortcut(
      intent: ${s.id}Intent(),
      phrases: [${s.phrases.map(([en]) => swiftString(en)).join(', ')}],
      shortTitle: ${swiftString(s.title[0])},
      systemImageName: ${swiftString(s.icon)}
    )`
  ).join('\n');
  return `// Generated by plugins/with-shortcuts.js. Edit the plugin, not this file.
import AppIntents
import Foundation

/// Opens the app on \`route\`. The MubayanGlasses module reads the route and tells JS.
protocol RouteIntent: AppIntent {
  static var route: String { get }
}

extension RouteIntent {
  static var openAppWhenRun: Bool { true }

  @MainActor
  func perform() async throws -> some IntentResult {
    UserDefaults.standard.set(Self.route, forKey: "mubayan.pendingShortcut")
    NotificationCenter.default.post(name: Notification.Name("MubayanShortcut"), object: nil)
    return .result()
  }
}

${intents}

struct MubayanShortcuts: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
${shortcuts}
  }
}
`;
}

function catalog(pairs) {
  const strings = {};
  for (const [en, ar] of pairs) {
    strings[en] = { localizations: { ar: { stringUnit: { state: 'translated', value: ar } } } };
  }
  return JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2) + '\n';
}

/** @type {import('expo/config-plugins').ConfigPlugin<{ alternativeNames?: string[] }>} */
module.exports = function withShortcuts(config, { alternativeNames = [] } = {}) {
  config = withInfoPlist(config, (cfg) => {
    // Lets Siri match "Mubayan" as well as the full display name.
    if (alternativeNames.length) cfg.modResults.INAlternativeAppNames = alternativeNames.map((name) => ({ INAlternativeAppName: name }));
    return cfg;
  });

  config = withDangerousMod(config, [
    'ios',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot));
      fs.writeFileSync(path.join(dir, SWIFT_FILE), swiftSource());
      fs.writeFileSync(path.join(dir, PHRASES_FILE), catalog(SHORTCUTS.flatMap((s) => s.phrases)));
      fs.writeFileSync(path.join(dir, TITLES_FILE), catalog(SHORTCUTS.map((s) => s.title)));
      return cfg;
    },
  ]);

  config = withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const add = (file, resource) => {
      const filepath = `${name}/${file}`;
      if (project.hasFile(filepath)) return;
      if (resource) IOSConfig.XcodeUtils.addResourceFileToGroup({ filepath, groupName: name, project, isBuildFile: true });
      else IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: name, project });
    };
    add(SWIFT_FILE, false);
    add(PHRASES_FILE, true);
    add(TITLES_FILE, true);

    // Without the string-catalog type Xcode copies the .xcstrings as-is instead of compiling it.
    const refs = project.pbxFileReferenceSection();
    for (const ref of Object.values(refs)) {
      if (typeof ref === 'object' && /\.xcstrings"?$/.test(String(ref.path))) ref.lastKnownFileType = 'text.json.xcstrings';
    }

    // Arabic has to be a known region for the Arabic phrases to be built into the app.
    const root = project.getFirstProject().firstProject;
    if (!root.knownRegions.includes('ar')) root.knownRegions.push('ar');
    return cfg;
  });

  return config;
};
