const DICTS: Record<Lang, Dict> = { ar, en };

export const LANG_NAMES: Record<Lang, string> = { ar: 'العربية', en: 'English' };

export function useI18n() {
  const { settings } = useSettings();
  const lang = settings.lang;
  return {
    lang,
    t: DICTS[lang],
    dir: (lang === 'ar' ? 'rtl' : 'ltr') as 'rtl' | 'ltr',
    /** BCP‑47 voice for expo-speech. */
    speechLang: lang === 'ar' ? 'ar-SA' : 'en-US',
  };
}

/** Picks the TTS voice from the text itself, so old answers replay in the language they were written in. */
export function voiceFor(text: string) {
  return /[؀-ۿ]/.test(text) ? 'ar-SA' : 'en-US';
}
